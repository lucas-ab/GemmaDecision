def slurp_canonical(label: str) -> str | None:
    """Canonical (MASSIVE) intent for a SLURP label, or None when the label is ambiguous or not a real intent."""
    if label in ASSISTANT_INTENTS:
        return label
    return SLURP_LEGACY.get(label)


