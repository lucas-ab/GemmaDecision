def describe(table: dict[str, str], source: str):
    """Lookup that fails loudly: a label without a description is a bug, not a fallback."""
    def f(label: str) -> str:
        if label not in table:
            raise KeyError(f"{source}: no description for label {label!r}")
        return table[label]
    return f
